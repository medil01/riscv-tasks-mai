.data
    prompt: .string "Введите число для массива: "
    # Выделяем ровно 96 байт под массив (16 + 8 = 24 элемента по 4 байта каждый)
    array: .space 96 

.text
.globl main
main:
    la t0, array        # t0 = базовый адрес начала массива в памяти
    li t1, 0            # t1 = текущий счетчик элементов (i = 0)
    li t2, 24           # t2 = максимальный лимит элементов (16 + n = 24)

read_loop:
    # Проверка на переполнение массива: если i == 24, останавливаем ввод
    beq t1, t2, end_loop

    # Печать приглашения к вводу
    li a7, 4            # print_string
    la a0, prompt
    ecall

    # Чтение очередного числа
    li a7, 5            # read_int
    ecall               # Введенное значение находится в a0

    # Проверка условия досрочного выхода: если введен 0, прекращаем цикл
    beqz a0, end_loop

    # Сохранение элемента в ячейку памяти
    sw a0, 0(t0)        # Записываем число по текущему адресу указателя
    addi t0, t0, 4      # Сдвигаем адресный указатель на 4 байта вперед для следующего числа
    addi t1, t1, 1      # Инкрементируем счетчик: i++
    j read_loop

end_loop:
    # Завершение работы программы
    li a7, 10
    ecall
